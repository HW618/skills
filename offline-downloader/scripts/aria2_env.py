#!/usr/bin/env python3
"""Shared aria2 RPC settings for the offline-downloader skill.

The daemon listens on loopback only and authenticates with a secret stored in
a skill-local config file. The secret is not placed on the aria2c command line.
"""

import json
import os
import secrets
import stat
import subprocess
import sys
import time
import urllib.error
import urllib.request

RPC_PORT = 6800
RPC_HOST = "127.0.0.1"


def skill_dir() -> str:
    """Directory that contains this skill (parent of scripts/)."""
    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def download_dir() -> str:
    return os.path.join(skill_dir(), "downloads")


def rpc_conf_path() -> str:
    return os.path.join(skill_dir(), ".aria2-rpc.conf")


def pip_install_argv(force: bool = False) -> list[str]:
    """Install aria2p into the interpreter that is running this skill."""
    cmd = [sys.executable, "-m", "pip", "install", "aria2p"]
    if force:
        cmd.append("--force-reinstall")
    return cmd


def daemon_argv(conf_path: str) -> list[str]:
    return ["aria2c", f"--conf-path={conf_path}", "--daemon=true"]


def _parse_conf(text: str) -> dict[str, str]:
    values: dict[str, str] = {}
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, value = stripped.split("=", 1)
        values[key.strip()] = value.strip()
    return values


def _write_private(path: str, text: str) -> None:
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write(text)
    try:
        os.chmod(path, stat.S_IRUSR | stat.S_IWUSR)
    except OSError:
        pass


def ensure_rpc_conf() -> tuple[str, str]:
    """Create or repair the loopback RPC config. Returns (path, secret)."""
    path = rpc_conf_path()
    existing: dict[str, str] = {}
    if os.path.exists(path):
        with open(path, encoding="utf-8") as handle:
            existing = _parse_conf(handle.read())
    secret = existing.get("rpc-secret") or secrets.token_urlsafe(24)
    body = "\n".join([
        "# Generated by offline-downloader. RPC stays on loopback and requires this secret.",
        "enable-rpc=true",
        "rpc-listen-all=false",
        f"rpc-listen-port={RPC_PORT}",
        "rpc-allow-origin-all=false",
        f"rpc-secret={secret}",
        f"dir={download_dir()}",
        "",
    ])
    _write_private(path, body)
    return path, secret


def rpc_ready(secret: str, port: int = RPC_PORT) -> bool:
    """Return True when the local daemon accepts this RPC secret."""
    payload = json.dumps({
        "jsonrpc": "2.0",
        "id": "offline-downloader",
        "method": "aria2.getVersion",
        "params": [f"token:{secret}"],
    }).encode("utf-8")
    request = urllib.request.Request(
        f"http://{RPC_HOST}:{port}/jsonrpc",
        data=payload,
        headers={"Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(request, timeout=2) as response:
            data = json.loads(response.read().decode("utf-8", "replace"))
    except (OSError, urllib.error.URLError, json.JSONDecodeError, ValueError):
        return False
    return isinstance(data, dict) and "result" in data


def _process_lines() -> list[str]:
    try:
        result = subprocess.run(
            ["ps", "aux"],
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError:
        return []
    return result.stdout.splitlines()


def foreign_rpc_daemon(conf_path: str) -> bool:
    """True when some other aria2c RPC process is up, and ours is not."""
    ours = False
    other = False
    for line in _process_lines():
        if "aria2c" not in line:
            continue
        if conf_path in line:
            ours = True
        elif "enable-rpc" in line or "rpc-listen" in line:
            other = True
    return other and not ours


def start_daemon() -> tuple[bool, str]:
    """Start aria2c on loopback with the skill RPC secret."""
    conf_path, secret = ensure_rpc_conf()
    if rpc_ready(secret):
        return True, "aria2c 守护进程已在运行"
    if foreign_rpc_daemon(conf_path):
        return False, (
            "检测到未使用本技能 RPC 配置的 aria2c。"
            "请先停止该进程，再重新初始化，避免继续使用无密钥且监听所有网卡的实例。"
        )
    result = subprocess.run(
        daemon_argv(conf_path),
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        detail = (result.stderr or result.stdout or "aria2c 启动失败").strip()
        return False, f"aria2c 守护进程启动失败: {detail}"
    for _ in range(10):
        if rpc_ready(secret):
            return True, "aria2c 守护进程启动成功"
        time.sleep(0.3)
    return False, "aria2c 守护进程启动失败"
